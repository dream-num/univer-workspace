import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// <id>-<version>-<base64 payload>-<base64 signature>-<timestamp>
const LICENSE_PATTERN = /^\d+-\d+-([A-Za-z0-9+/=]+)-[A-Za-z0-9+/=]+-\d+$/u;
const LICENSE_KEY_PATTERN = /^[A-Za-z0-9+/=]+$/u;

// Every application-owned copy of the Univer runtime license. Each file is
// regenerated as a whole, so rotating the license never needs a manual edit.
// The Web SDK only accepts the license; server-side Collaboration and Exchange
// SDKs also verify it with the license key.
export const LICENSE_TARGETS = [
  {
    path: "apps/mcp/src/executor/license.ts",
    subject: "executor runtime development license",
    constants: { UNIVER_LICENSE: "license", UNIVER_LICENSE_KEY: "licenseKey" },
  },
  {
    path: "apps/workspace/web/src/features/editor/features/license.ts",
    subject: "browser runtime development license",
    constants: { UNIVER_LICENSE: "license" },
  },
  {
    path: "apps/workspace/server/src/integrations/univer/license.ts",
    subject: "server Collaboration and Exchange development license",
    constants: { UNIVER_LICENSE: "license", UNIVER_LICENSE_KEY: "licenseKey" },
  },
  {
    path: "apps/cli/src/license.ts",
    subject: "runtime development license",
    constants: { UNIVER_LICENSE: "license", UNIVER_LICENSE_KEY: "licenseKey" },
  },
  {
    // Client Core receives credentials from its Client Shell; its own tests
    // need a licensed pair so real exports do not consume the free-tier quota.
    path: "packages/client-core/test/license.ts",
    subject: "development license for Client Core tests",
    constants: { UNIVER_LICENSE: "license", UNIVER_LICENSE_KEY: "licenseKey" },
  },
  {
    path: "packages/dsh-univer-workspace-plugin/src/license.ts",
    subject: "runtime development license fallback when no config/env license is set",
    constants: { DEVELOPMENT_LICENSE: "license", DEVELOPMENT_LICENSE_KEY: "licenseKey" },
  },
];

export function parseLicenseUpdateArgs(argv) {
  const args = argv.filter((argument) => argument !== "--");
  const options = {};
  for (let index = 0; index < args.length; index += 1) {
    const [flag, inline] = args[index].split(/=(.*)/su);
    const value = inline ?? args[(index += 1)];
    if ((flag !== "--license" && flag !== "--license-key") || !value) {
      throw new Error(
        "License update requires --license <license.txt> --license-key <licenseKey.txt>.",
      );
    }
    options[flag === "--license" ? "license" : "licenseKey"] = value;
  }
  if (options.license === undefined || options.licenseKey === undefined) {
    throw new Error(
      "License update requires --license <license.txt> --license-key <licenseKey.txt>.",
    );
  }
  return options;
}

/** Validate the credentials and read the public payload fields used in comments. */
export function describeLicense(license, licenseKey) {
  const match = LICENSE_PATTERN.exec(license);
  if (match === null) throw new Error("License file does not contain a Univer license.");
  if (!LICENSE_KEY_PATTERN.test(licenseKey)) {
    throw new Error("License key file does not contain a Univer license key.");
  }
  const payload = readLeadingJson(Buffer.from(match[1], "base64").toString("latin1"));
  if (
    !Number.isSafeInteger(payload.at) ||
    !Number.isSafeInteger(payload.ud) ||
    !Array.isArray(payload.dm)
  ) {
    throw new Error("License payload is missing its issue time, expiry or domains.");
  }
  return {
    issuedAt: new Date(payload.at * 1000).toISOString().replace(".000Z", "Z"),
    expiresAt: new Date(payload.ud * 1000).toISOString().replace(".000Z", "Z"),
    domains: payload.dm.map(String),
  };
}

export function renderLicenseModule(target, credentials, details) {
  const lines = [
    "// Generated by `pnpm update:univer-license`; do not edit by hand.",
    "/**",
    ` * Application-owned Univer ${target.subject}.`,
    ` * Issued ${details.issuedAt}; expires ${details.expiresAt}. Rotate before expiry.`,
    ` * Authorized domains: ${details.domains.join(", ")}.`,
    " */",
  ];
  for (const [name, field] of Object.entries(target.constants)) {
    lines.push(`export const ${name} =`, `  ${JSON.stringify(credentials[field])};`);
  }
  return `${lines.join("\n")}\n`;
}

function readLeadingJson(decoded) {
  // Tolerate trailing bytes after the JSON object.
  let depth = 0;
  for (let index = 0; index < decoded.length; index += 1) {
    if (decoded[index] === "{") depth += 1;
    else if (decoded[index] === "}" && --depth === 0) {
      return JSON.parse(decoded.slice(0, index + 1));
    }
  }
  throw new Error("License payload is not a JSON object.");
}

export async function main(argv) {
  const options = parseLicenseUpdateArgs(argv);
  const credentials = {
    license: (await readFile(resolve(options.license), "utf8")).trim(),
    licenseKey: (await readFile(resolve(options.licenseKey), "utf8")).trim(),
  };
  const details = describeLicense(credentials.license, credentials.licenseKey);
  for (const target of LICENSE_TARGETS) {
    await writeFile(
      join(REPO_ROOT, target.path),
      renderLicenseModule(target, credentials, details),
      "utf8",
    );
  }
  process.stdout.write(
    `Wrote the Univer license issued ${details.issuedAt} (expires ${details.expiresAt}, ` +
      `domains: ${details.domains.join(", ")}) to ${LICENSE_TARGETS.length} files.\n`,
  );
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main(process.argv.slice(2));
}
