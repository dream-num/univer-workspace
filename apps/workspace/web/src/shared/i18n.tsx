const englishPluralRules = new Intl.PluralRules("en-US");

export type ModeMessages = Partial<Record<AppLanguage, Partial<Record<MessageKey, string>>>>;

interface LanguageContextValue {
  readonly language: AppLanguage;
  readonly setLanguage: (language: AppLanguage) => void;
  readonly t: (key: MessageKey, values?: Readonly<Record<string, string | number>>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const STORAGE_KEY = "univer-workspace-language";

export function browserLanguage(preferences: readonly string[]): AppLanguage {
  for (const preference of preferences) {
    const primary = preference.toLowerCase().split("-")[0];
    if (primary === "zh") return "zh-CN";
    if (primary === "en") return "en-US";
  }
  return "en-US";
}

function initialLanguage(): AppLanguage {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "zh-CN" || stored === "en-US") return stored;
  } catch {
    // Fall back to the browser preference when storage is unavailable.
  }
  return browserLanguage(navigator.languages ?? [navigator.language]);
}

export function LanguageProvider({
  children,
  overrides,
}: PropsWithChildren<{ readonly overrides?: ModeMessages }>) {
  const [language, setCurrentLanguage] = useState<AppLanguage>(initialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((next: AppLanguage) => {
    setCurrentLanguage(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The choice still applies for the current page.
    }
  }, []);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t(key, values) {
        const override = overrides?.[language]?.[key];
        const count = values?.[key === "filteredItemsCount" ? "total" : "count"];
        const singular = language === "en-US" && typeof count === "number" && englishPluralRules.select(count) === "one"
          ? englishSingularMessages[key]
          : undefined;
        let value: string = singular ?? override ?? messages[language][key];
        for (const [name, replacement] of Object.entries(values ?? {})) {
          value = value.replaceAll(`{${name}}`, String(replacement));
        }
        return value;
      },
    }),
    [language, setLanguage, overrides],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) {
    throw new Error("useI18n must be used within LanguageProvider");
  }
  return value;
}
