import { writeEvidence } from './evidence-output.mjs';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const log = await readFile(process.env.SPACE_DSH_LOG ?? '/tmp/task004-dsh.log', 'utf8');
const tokenURL = log.match(/dsh web: (https?:\/\/\S+)/)?.[1];
if (!tokenURL) throw new Error('Point SPACE_DSH_LOG at the private launcher log.');
const origin = new URL(tokenURL).origin;
const checks = [];
const anonymous = await fetch(`${origin}/space-plugin/api/status`);
assert.equal(anonymous.status, 401); checks.push({ name: 'unauthenticated DSH browser rejected', status: anonymous.status });
const admission = await fetch(tokenURL, { redirect: 'manual' });
const cookie = admission.headers.getSetCookie().map(value => value.split(';')[0]).join('; ');
assert.ok(cookie);
const admitted = await fetch(`${origin}/space-plugin/api/status`, { headers: { cookie } });
assert.equal(admitted.status, 200); const status = await admitted.json();
assert.equal(status.state, 'connected'); checks.push({ name: 'authenticated DSH browser sees connected Workspace', status: admitted.status });
const crossOrigin = await fetch(`${origin}/space-plugin/api/status`, { headers: { cookie, origin: 'https://untrusted.example' } });
assert.equal(crossOrigin.status, 403); checks.push({ name: 'cross-origin browser rejected', status: crossOrigin.status });
await writeEvidence('host-api.json', { at: new Date().toISOString(), origin, checks });
console.log(JSON.stringify({ passed: checks.length, checks }));
